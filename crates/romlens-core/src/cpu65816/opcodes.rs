//! The 256-entry opcode table, written as the sixteen rows of the WDC matrix.
//!
//! Column pattern for the eight "A-op" rows (`$0x ORA`, `$2x AND`, `$4x EOR`,
//! `$6x ADC`, `$8x STA`, `$Ax LDA`, `$Cx CMP`, `$Ex SBC`): even row x1 `(dp,X)`,
//! x3 `sr,S`, x5 `dp`, x7 `[dp]`, x9 `#imm`, xD `abs`, xF `long`; odd row x1
//! `(dp),Y`, x2 `(dp)`, x3 `(sr,S),Y`, x5 `dp,X`, x7 `[dp],Y`, x9 `abs,Y`, xD
//! `abs,X`, xF `long,X`. `$89` is `BIT #imm`. The even-row x2 column holds
//! COP / JSL / WDM / PER / BRL / LDX # / REP / SEP; `$44` MVP, `$54` MVN; jumps
//! `$4C $5C $6C $7C $DC $20 $FC`; `$F4` PEA, `$D4` PEI.

use crate::cpu65816::mnemonic::Mnemonic;
use crate::cpu65816::mode::AddressingMode;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct OpcodeInfo {
    pub mnemonic: Mnemonic,
    pub mode: AddressingMode,
}

const fn op(mnemonic: Mnemonic, mode: AddressingMode) -> OpcodeInfo {
    OpcodeInfo { mnemonic, mode }
}

