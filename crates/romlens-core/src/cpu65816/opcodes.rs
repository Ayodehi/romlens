/// The opcode for a mnemonic in a mode, when the pair exists.
pub fn opcode_for(mnemonic: Mnemonic, mode: AddressingMode) -> Option<u8> {
    OPCODES
        .iter()
        .position(|o| o.mnemonic == mnemonic && o.mode == mode)
        .map(|i| i as u8)
}
