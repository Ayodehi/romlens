pub fn number(id: &str) -> Option<&'static Number> {
    NUMBERS.iter().find(|f| f.id == id)
}

pub fn said(id: &str) -> Option<&'static Said> {
    SAIDS.iter().find(|f| f.id == id)
}

pub fn listed<T: Copy>(table: &[(&str, &'static [T])], concept: &str) -> &'static [T] {
    table
        .iter()
        .find(|(c, _)| *c == concept)
        .map_or(&[], |(_, v)| v)
}

#[cfg(test)]
mod tests {
    use super::*;
    use romlens_core::graphics::{oam::OAM_LEN, palette::CGRAM_LEN, render::VRAM_LEN};
    use romlens_core::timing;

    #[test]
    fn numbers_agree_with_the_core() {
        let is = |id: &str, v: u32| assert_eq!(number(id).unwrap().answer, v, "{id}");
        is("oam_bytes", OAM_LEN as u32);
        is("cgram_bytes", CGRAM_LEN as u32);
        is("colours", CGRAM_LEN as u32 / 2);
        is("vram_kb", VRAM_LEN as u32 / 1024);
        is("lines", timing::LINES_NTSC as u32);
        is("visible", timing::VISIBLE as u32);
        is("vblank_start", timing::VBLANK_START as u32);
        is("master_line", timing::MASTER_PER_LINE);
        is("dots", timing::DOTS as u32);
        is("sprites", (OAM_LEN as u32 - 32) / 4);
    }

    #[test]
    fn every_entry_is_on_the_map() {
        let on_map = |c: &str| romlens_tutor::lesson::concept(c).is_some();
        for f in NUMBERS {
            assert!(on_map(f.concept) && (1..=5).contains(&f.level), "{}", f.id);
        }
        for f in SAIDS {
            assert!(on_map(f.concept) && (1..=5).contains(&f.level), "{}", f.id);
            assert!(
                f.wrong.len() >= 2 && !f.wrong.contains(&f.answer),
                "{}",
                f.id
            );
        }
        let mut ids: Vec<&str> = NUMBERS
            .iter()
            .map(|f| f.id)
            .chain(SAIDS.iter().map(|f| f.id))
            .collect();
        let n = ids.len();
        ids.sort_unstable();
        ids.dedup();
        assert_eq!(ids.len(), n, "an id is used twice");
        for (c, _) in CONCEPT_REGISTERS
            .iter()
            .chain(CONCEPT_DSP)
            .chain(CONCEPT_MNEMONICS)
            .chain(CONCEPT_TERMS)
        {
            assert!(on_map(c), "{c}");
        }
    }
}
