/// A statement: the prompt, the right answer and wrong ones.
pub struct Said {
    pub id: &'static str,
    pub concept: &'static str,
    pub level: u8,
    pub prompt: &'static str,
    pub answer: &'static str,
    pub wrong: &'static [&'static str],
    pub explain: &'static str,
}

const fn s(
    id: &'static str,
    concept: &'static str,
    level: u8,
    prompt: &'static str,
    answer: &'static str,
    wrong: &'static [&'static str],
    explain: &'static str,
) -> Said {
    Said {
        id,
        concept,
        level,
        prompt,
        answer,
        wrong,
        explain,
    }
}

