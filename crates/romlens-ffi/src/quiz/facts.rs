//! What Romlens's level 1 and 2 questions ask (docs/28): numbers traced to
//! the core's constants and tables, statements with their wrong answers,
//! and each concept's registers, instructions and glossary terms.
//!
//! Every entry is checked by `claims`: a number against its table, a
//! register or instruction against the core's. The statements are ours,
//! in the primer's words (`04-snes-technical-primer.md`).

/// A number to know.
pub struct Number {
    pub id: &'static str,
    pub concept: &'static str,
    pub level: u8,
    pub prompt: &'static str,
    pub answer: u32,
    /// Typed and shown as hex (an address).
    pub hex: bool,
    pub explain: &'static str,
}

const fn n(
    id: &'static str,
    concept: &'static str,
    level: u8,
    prompt: &'static str,
    answer: u32,
    explain: &'static str,
) -> Number {
    Number {
        id,
        concept,
        level,
        prompt,
        answer,
        hex: false,
        explain,
    }
}

